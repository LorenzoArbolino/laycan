"""Build historical replay episodes from public EIA data (via FRED and the EIA API).

Each episode stores, per business day, the benchmark components the engine replays:
Brent spot, US Gulf cracks (gasoline, diesel, jet) and NYH − USGC differentials, plus the
weekly US stock deviation from its 5-year seasonal mean (drives curve structure).
Everything else (other hubs, freight, curves) is generated by the model around these.

Output: params/replay.json   Run: uv run python replay.py
"""

from __future__ import annotations

import datetime as dt
import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "data" / "raw"
GAL = 42.0

# (id, start Monday, name, weeks): the length covers the event and its aftermath
EPISODES = [
    ("abqaiq_2019", "2019-08-26", "Abqaiq attack, autumn 2019", 19),
    ("gfc_2008", "2008-09-15", "Financial crisis, autumn 2008", 24),
    ("covid_2020", "2020-03-02", "COVID collapse, spring 2020", 18),
    ("uri_2021", "2021-02-08", "Texas freeze, winter 2021", 17),
    ("ukraine_2022", "2022-02-21", "Russia invades Ukraine, spring 2022", 20),
    ("squeeze_2022", "2022-10-03", "Diesel squeeze and price cap, autumn 2022", 20),
    ("redsea_2023", "2023-12-04", "Red Sea attacks, winter 2023-24", 14),
    ("hormuz_2026", "2026-02-23", "War with Iran and the Hormuz closure, 2026", 26),
]
LOOKBACK_DAYS = 90  # history shown on the charts before the episode starts


def fred(sid: str) -> pd.Series:
    df = pd.read_csv(RAW / "fred" / f"{sid}.csv")
    df.columns = ["date", sid]
    df["date"] = pd.to_datetime(df["date"])
    return pd.to_numeric(df.set_index("date")[sid], errors="coerce")


def stock_dev(sid: str) -> pd.Series:
    s = pd.read_csv(RAW / "eia" / f"{sid}.csv", parse_dates=["date"]).set_index("date")["value"].astype(float)
    wk = s.index.isocalendar().week.astype(int).values
    out = []
    for i, (d, v) in enumerate(s.items()):
        hist = s[(s.index.year >= d.year - 5) & (s.index.year < d.year)]
        hw = hist.index.isocalendar().week.astype(int).values
        m = hist[np.abs(hw - wk[i]) <= 1].mean()
        out.append((v / m - 1) * 100 if m == m else np.nan)
    return pd.Series(out, index=s.index)


def main() -> None:
    brent = fred("DCOILBRENTEU")
    px = pd.concat(
        sort=True,
        objs={
            "b": brent,
            "g": fred("DGASUSGULF") * GAL - brent,
            "d": fred("DDFUELUSGULF") * GAL - brent,
            "j": fred("DJFUELUSGULF") * GAL - brent,
            "ng": (fred("DGASNYH") - fred("DGASUSGULF")) * GAL,
            "nd": (fred("DDFUELNYH") - fred("DDFUELUSGULF")) * GAL,
        },
        axis=1,
    )
    stocks = pd.concat({"sd": stock_dev("WDISTUS1"), "sg": stock_dev("WGTSTUS1"), "sj": stock_dev("WKJSTUS1")}, axis=1)
    out = {
        "meta": {
            "generated": dt.date.today().isoformat(),
            "source": "U.S. EIA daily spot prices via FRED (DCOILBRENTEU, DGASUSGULF, DDFUELUSGULF, DJFUELUSGULF, DGASNYH, DDFUELNYH); EIA Weekly Petroleum Status Report stocks (WDISTUS1, WGTSTUS1, WKJSTUS1)",
            "fields": {
                "b": "Brent spot $/bbl",
                "g": "USGC gasoline crack vs Brent $/bbl",
                "d": "USGC ULSD crack vs Brent $/bbl",
                "j": "USGC jet crack vs Brent $/bbl",
                "ng": "NYH − USGC gasoline $/bbl",
                "nd": "NYH − USGC ULSD $/bbl",
                "sd": "US distillate stocks vs 5y same-week mean, %",
                "sg": "US gasoline stocks vs 5y same-week mean, %",
                "sj": "US jet stocks vs 5y same-week mean, %",
            },
        },
        "episodes": [],
    }
    for eid, start, name, weeks in EPISODES:
        s = pd.Timestamp(start)
        e = s + pd.Timedelta(days=7 * weeks + 21)  # room for voyages finishing after the game ends
        w = px.loc[s - pd.Timedelta(days=LOOKBACK_DAYS) : e].dropna()
        st = stocks.reindex(w.index, method="ffill")
        rows = []
        for d, r in w.iterrows():
            row = {"t": d.strftime("%Y-%m-%d")}
            for k in ["b", "g", "d", "j", "ng", "nd"]:
                row[k] = round(float(r[k]), 3)
            for k in ["sd", "sg", "sj"]:
                v = st.loc[d, k]
                row[k] = None if pd.isna(v) else round(float(v), 2)
            rows.append(row)
        out["episodes"].append({"id": eid, "name": name, "start": start, "weeks": weeks, "rows": rows})
        print(eid, len(rows), rows[0]["t"], rows[-1]["t"])
    (ROOT / "params" / "replay.json").write_text(json.dumps(out, separators=(",", ":")) + "\n")


if __name__ == "__main__":
    main()
